// 짱샘 채널 YouTube 썸네일 — Google Flow용 이미지 생성 프롬프트 빌더.
// 전체 강의 대본을 읽고 가장 강한 클릭 후크를 뽑아 시각 컨셉 + 한글 헤드라인이 담긴
// 단일 한국어 프롬프트를 출력. 사용자는 출력 결과를 Google Flow에 그대로 붙여넣어 이미지를 생성.

export interface ThumbnailPromptInput {
  topic: string;
  /** 슬라이드별 강의 대본 (idx -> text). 6번 단계 결과. */
  lectureScripts: Record<number, string>;
  research?: string;
}

const PERSONA = `당신은 짱샘 YouTube 채널의 썸네일 컨셉 디자이너입니다.
짱샘은 25년차 아동 재활치료사(소아발달 재활 전문가)이고, 발달장애·감각통합·수면·식이 등
부모 대상 콘텐츠를 만듭니다. 시청자는 영유아~초등 자녀를 둔 부모이며, 모바일 피드에서
스크롤하다가 멈춰서 클릭하게 만드는 게 목표입니다.`;

const PRINCIPLES = `썸네일 설계 원칙 (가장 중요 — 반드시 준수):

1. **전체 강의 대본을 처음부터 끝까지 읽는다.** 슬라이드 제목·일부만 보고 만들지 않는다.

2. **가장 강한 클릭 후크 1개를 대본 안에서 뽑는다.**
   - 부모가 피드에서 멈추고 "어? 우리 아이 얘긴가?" 하게 만들 만큼 구체적
   - 반전·의외성·자기진단 유도가 강한 신호 (예: "이 증상이 보이면", "대부분 모르는", "버릇이 아니라")
   - 영상이 실제로 약속하는 가치와 일치해야 함. 낚시·과장 금지.

3. **후크를 시각화하는 컨셉은 영상마다 새로 설계.** 정해진 레이아웃 공식 없음.
   - 어떤 영상은 비교(또렷↔흐릿), 어떤 영상은 표정 클로즈업, 어떤 영상은 행위 장면,
     어떤 영상은 메타포(빙산 등), 어떤 영상은 상황 재현 …
   - 대본 내용에 가장 잘 맞는 시각 표현을 그때그때 새로 정한다.
   - 시선 유도 장치(빨간 원, 화살표 등)는 콘텐츠상 자연스러우면 사용. 무조건 넣지 말 것.

4. **한글 헤드라인 카피 1~2줄을 함께 설계.**
   - 호기심 갭 + 구체 숫자 + 자기진단 유도 조합 권장 (강제 X)
   - 모바일에서도 한 번에 읽히는 짧고 강한 문장
   - 좋은 예 톤: "대부분은 모르는 / ADHD일때 보이는 특징 5가지", "이 증상이 보인다면??"

5. **강사 인물 컷 자리 (옵션):**
   - 짱샘 본인 사진을 사용자가 Google Flow의 reference 이미지로 합성할 가능성이 있음.
   - 우측 1/3 정도 영역을 비워두는 레이아웃을 권장하되 필수는 아님. 콘텐츠상 인물 컷이
     불필요하면 시각 컨셉이 풀 프레임으로 가도 좋다.
   - 인물 얼굴 묘사는 하지 말 것. "강사 인물 컷이 합성될 우측 영역 비워둠" 정도로 자리만 잡는다.

6. **출력 대상: Google Flow 이미지 생성 모델**
   - Flow는 한글 텍스트 렌더링이 잘 되므로 헤드라인 한글을 따옴표로 인용해서 그대로 명시.
   - 가로 16:9 (1280×720) 유튜브 썸네일 비율 명시.`;

const OUTPUT_FORMAT = `출력 형식 (반드시 준수):
- **자연스러운 한국어 문장으로 풀어 쓴 단일 프롬프트 텍스트만** 출력.
- 머리말, 꼬리말, 코멘트, 설명, 마크다운 헤더, 라벨(예: "이미지 컨셉:", "헤드라인:"),
  JSON, 코드 블록, "프롬프트:" 같은 접두어 — 모두 금지.
- 출력 안에 다음 요소가 자연스럽게 녹아 있어야 함:
  - 가로 16:9 (1280×720) 유튜브 썸네일 비율
  - 시각 컨셉 — 어떤 장면·구도·표정·소품·배경·색감을 어디에 배치할지
  - 한글 헤드라인 카피 — 큰 글씨로 박을 텍스트를 따옴표로 정확히 인용
    (예: 화면 하단에 굵은 한글로 "대부분은 모르는 ADHD 신호 5가지"라고 박는다)
  - 신뢰 배지·서브 텍스트 (선택, 예: "25년차 소아발달 재활 전문가" 우상단 등)
  - 강사 인물 컷 자리 (선택)
  - 타이포 스타일 — 굵은 한글 폰트, 노란 본문 + 검정 외곽선 등 모바일 가독성
  - 시선 유도 장치 (선택)
- 분량: 300~600자 사이 (너무 짧으면 디테일 부족, 너무 길면 모델이 헷갈림).`;

export function buildThumbnailPrompt(
  input: ThumbnailPromptInput
): { system: string; user: string } {
  const { topic, lectureScripts, research } = input;

  const entries = Object.entries(lectureScripts)
    .map(([k, v]) => [Number(k), (v ?? '').trim()] as const)
    .filter(([idx, v]) => Number.isFinite(idx) && v.length > 0)
    .sort((a, b) => a[0] - b[0]);

  const compiledScript = entries
    .map(([idx, v]) => `[슬라이드 ${idx + 1}]\n${v}`)
    .join('\n\n');

  const system = [PERSONA, '', PRINCIPLES, '', OUTPUT_FORMAT].join('\n');

  const researchBlock =
    research && research.trim()
      ? [
          '',
          '== 리서치 (참고만 — 후크는 대본에서 뽑을 것) ==',
          research.trim().slice(0, 4000),
          '',
        ].join('\n')
      : '';

  const user = [
    `영상 주제: ${topic}`,
    researchBlock,
    '== 전체 강의 대본 (이걸 다 읽고 클릭 후크를 뽑으세요) ==',
    compiledScript,
    '',
    '위 대본 전체를 읽고, 시청자(부모)가 클릭하고 싶어지는 가장 강력한 후크 1개를 뽑아',
    'Google Flow 이미지 생성 모델에 그대로 붙여넣을 단일 한국어 프롬프트를 출력하세요.',
    '머리말·꼬리말·코멘트 없이 프롬프트 본문만, 자연스러운 한국어 문장으로.',
  ].filter(Boolean).join('\n');

  return { system, user };
}
