/**
 * 슬라이드 단독 감사(audit) 출력에서 혹시 모델이 붙인 "## 슬라이드 N" 헤더를 제거.
 */
export function stripLectureSlideHeader(text: string): string {
  return text.replace(/^\s*#{1,3}\s*슬라이드\s*\d+\s*\n+/i, '').trim();
}

/**
 * 강의 대본 본문 첫 1줄을 한 줄 요약으로 압축 (audit 패스의 전·후 슬라이드 컨텍스트용).
 */
export function summarizeSlideScript(text: string, maxLen = 80): string {
  const firstSentence = text
    .replace(/\s+/g, ' ')
    .split(/[.!?。！？]/)
    .map((s) => s.trim())
    .find((s) => s.length > 0);
  if (!firstSentence) return '';
  return firstSentence.length > maxLen
    ? firstSentence.slice(0, maxLen) + '…'
    : firstSentence;
}

/**
 * Claude/사용자가 작성한 강의 대본 텍스트를 슬라이드별 본문으로 분리.
 * "## 슬라이드 N" 헤더 기준 split.
 */
export function parseLectureScript(text: string): Record<number, string> {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const out: Record<number, string> = {};
  let currentIdx: number | null = null;
  let buffer: string[] = [];

  const flush = () => {
    if (currentIdx !== null) {
      out[currentIdx] = buffer.join('\n').trim();
    }
  };

  const HEADER = /^#{1,3}\s*(?:슬라이드\s*)?(\d+)\b/;
  for (const line of lines) {
    const m = line.trim().match(HEADER);
    if (m) {
      flush();
      currentIdx = Number(m[1]) - 1;
      buffer = [];
    } else {
      buffer.push(line);
    }
  }
  flush();

  return out;
}
